"""Project document archive + local datasheet library + client package.

Everything lives under ``DATA_DIR`` on the installer's own server (served read-only at ``/api/files/<path>``):

* ``projects/<project id>/<kind>/<timestamp>_<filename>`` — every generated quote/techfile/calc/BOM/RFQ/order is
  archived automatically when it is produced (``archive``; identical content is not stored twice), plus photos,
  contracts and protocols uploaded by the user (``store_upload``).
* ``datasheets/<sha1>.pdf`` — mirrored manufacturer datasheets and Aerocompact manuals (``mirror_datasheets``), so the
  quote package and the tech file never depend on an external server being online.
"""
from __future__ import annotations

import hashlib
import io
import mimetypes
import re
import threading
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from sqlalchemy.orm import Session

from ..config import get_settings
from ..models import CatalogItem, Project, ProjectDocument, Quote
from .supplier_sync import cached_datasheet, datasheet_cache_dir

KINDS = ("quote", "calc", "techfile", "bom", "rfq", "order", "photo", "survey", "contract", "datasheet", "protocol", "other")
KIND_LABELS_BG = {"quote": "Оферта", "calc": "Калкулация", "techfile": "Техническо досие", "bom": "КСС / BOM", "rfq": "Запитване", "order": "Поръчка",
                  "photo": "Снимка", "survey": "Оглед", "contract": "Договор", "datasheet": "Datasheet", "protocol": "Протокол", "other": "Друго"}


def _safe_name(name: str) -> str:
    name = re.sub(r"[^\w\-. ()]+", "_", name, flags=re.U).strip(" _")
    return (name or "file")[:120]


def _project_dir(project_id: int, kind: str) -> Path:
    d = get_settings().data_dir / "projects" / str(project_id) / kind
    d.mkdir(parents=True, exist_ok=True)
    return d


def _sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def archive(db: Session, project: Project, kind: str, filename: str, data: bytes, *, quote: Quote | None = None, title: str | None = None,
            user_id: int | None = None, notes: str | None = None) -> ProjectDocument:
    """Store generated bytes as a new document version. If the newest document of the same kind/quote/filename has the
    same content, it is returned instead of creating a duplicate."""
    kind = kind if kind in KINDS else "other"
    digest = _sha1(data)
    last = (db.query(ProjectDocument).filter(ProjectDocument.project_id == project.id, ProjectDocument.kind == kind, ProjectDocument.filename == filename)
            .order_by(ProjectDocument.id.desc()).first())
    if last and (last.notes or "").startswith("sha1:" + digest):
        return last
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    fn = f"{stamp}_{_safe_name(filename)}"
    dest = _project_dir(project.id, kind) / fn
    dest.write_bytes(data)
    doc = ProjectDocument(project_id=project.id, quote_id=quote.id if quote else None, kind=kind, title=title or filename, filename=filename,
                          path=str(dest.relative_to(get_settings().data_dir)).replace("\\", "/"), size=len(data),
                          mime=mimetypes.guess_type(filename)[0] or "application/octet-stream", notes=f"sha1:{digest}" + (f" {notes}" if notes else ""), created_by=user_id)
    db.add(doc)
    db.flush()
    return doc


def archive_file(db: Session, project: Project, kind: str, path: Path, filename: str, **kw: Any) -> ProjectDocument:
    return archive(db, project, kind, filename, Path(path).read_bytes(), **kw)


def store_upload(db: Session, project: Project, kind: str, filename: str, data: bytes, *, user_id: int | None, title: str | None = None,
                 notes: str | None = None, quote_id: int | None = None) -> ProjectDocument:
    kind = kind if kind in KINDS else "other"
    if kind == "photo":
        data, filename = _shrink_photo(data, filename)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    dest = _project_dir(project.id, kind) / f"{stamp}_{_safe_name(filename)}"
    dest.write_bytes(data)
    doc = ProjectDocument(project_id=project.id, quote_id=quote_id, kind=kind, title=title or filename, filename=filename,
                          path=str(dest.relative_to(get_settings().data_dir)).replace("\\", "/"), size=len(data),
                          mime=mimetypes.guess_type(filename)[0] or "application/octet-stream", notes=notes, created_by=user_id)
    db.add(doc)
    db.flush()
    return doc


def _shrink_photo(data: bytes, filename: str) -> tuple[bytes, str]:
    try:
        from PIL import Image, ImageOps

        img = Image.open(io.BytesIO(data))
        img = ImageOps.exif_transpose(img).convert("RGB")
        if max(img.size) > 2400:
            img.thumbnail((2400, 2400))
        buf = io.BytesIO()
        img.save(buf, "JPEG", quality=86)
        return buf.getvalue(), re.sub(r"\.[^.]+$", "", filename) + ".jpg"
    except Exception:  # noqa: BLE001 – not an image we can read: keep as is
        return data, filename


def delete(db: Session, doc: ProjectDocument) -> None:
    p = get_settings().data_dir / doc.path
    try:
        if p.exists():
            p.unlink()
    except OSError:
        pass
    db.delete(doc)


def doc_dict(d: ProjectDocument) -> dict[str, Any]:
    return {"id": d.id, "project_id": d.project_id, "quote_id": d.quote_id, "kind": d.kind, "kind_label": KIND_LABELS_BG.get(d.kind, d.kind), "title": d.title,
            "filename": d.filename, "path": d.path, "url": f"/api/files/{d.path}", "size": d.size, "mime": d.mime,
            "notes": re.sub(r"^sha1:[0-9a-f]+\s?", "", d.notes or "") or None, "created_at": d.created_at.isoformat() if d.created_at else None, "created_by": d.created_by}


# ----------------------------------------------------------------------------- datasheets / library
def _item_urls(ci: CatalogItem) -> list[str]:
    sp = ci.specs or {}
    urls: list[str] = []
    for u in [sp.get("datasheet_url")] + list(sp.get("datasheet_urls") or []):
        if u and isinstance(u, str) and u.lower().startswith("http") and u not in urls:
            urls.append(u)
    return urls


def library_docs() -> list[dict[str, str]]:
    """Aerocompact manuals / leaflets / checklists shipped with the catalog module."""
    from ..seed_data.aerocompact import DOCS

    out: list[dict[str, str]] = []
    for system, docs in DOCS.items():
        for key, url in docs.items():
            if url.lower().endswith(".pdf"):
                out.append({"system": system, "doc": key, "url": url, "title": f"Aerocompact {system} — {key.replace('_', ' ')}"})
    return out


def local_path_for_url(url: str) -> Path | None:
    return cached_datasheet(url, get_settings().data_dir, download=False)


def datasheet_status(db: Session) -> dict[str, Any]:
    items = db.query(CatalogItem).all()
    with_url = [i for i in items if _item_urls(i)]
    local = 0
    for i in with_url:
        sp = i.specs or {}
        if sp.get("datasheet_file") and (datasheet_cache_dir(get_settings().data_dir) / sp["datasheet_file"]).exists():
            local += 1
        elif any(local_path_for_url(u) for u in _item_urls(i)):
            local += 1
    lib = library_docs()
    lib_local = sum(1 for d in lib if local_path_for_url(d["url"]))
    uploaded = sum(1 for i in items if (i.specs or {}).get("datasheet_file") and not _item_urls(i))
    d = datasheet_cache_dir(get_settings().data_dir)
    size = sum(p.stat().st_size for p in d.glob("*.pdf")) if d.exists() else 0
    return {"items_with_url": len(with_url), "items_local": local, "items_uploaded_only": uploaded, "library_total": len(lib), "library_local": lib_local,
            "files": len(list(d.glob("*.pdf"))) if d.exists() else 0, "size_mb": round(size / 1e6, 1), "running": _MIRROR["running"], "progress": dict(_MIRROR)}


_MIRROR: dict[str, Any] = {"running": False, "total": 0, "done": 0, "ok": 0, "failed": 0, "started_at": None, "finished_at": None, "current": None, "errors": []}
_LOCK = threading.Lock()


def mirror_datasheets(db_factory, only_missing: bool = True) -> bool:
    """Start the background download of every datasheet / manual URL into DATA_DIR/datasheets. Returns False if a run is
    already in progress. Progress is read via ``datasheet_status()``."""
    with _LOCK:
        if _MIRROR["running"]:
            return False
        _MIRROR.update({"running": True, "total": 0, "done": 0, "ok": 0, "failed": 0, "started_at": datetime.now(timezone.utc).isoformat(), "finished_at": None, "current": None, "errors": []})

    def run() -> None:
        import httpx

        from .supplier_sync import USER_AGENT

        data_dir = get_settings().data_dir
        try:
            with db_factory() as db:
                items = db.query(CatalogItem).all()
                jobs: list[tuple[int | None, str]] = []
                for ci in items:
                    for u in _item_urls(ci):
                        if only_missing and local_path_for_url(u):
                            if not (ci.specs or {}).get("datasheet_file"):
                                jobs.append((ci.id, u))  # just link the existing file
                            continue
                        jobs.append((ci.id, u))
                for d in library_docs():
                    if not (only_missing and local_path_for_url(d["url"])):
                        jobs.append((None, d["url"]))
                _MIRROR["total"] = len(jobs)
                client = httpx.Client(timeout=120, headers={"User-Agent": USER_AGENT}, follow_redirects=True)
                for item_id, url in jobs:
                    _MIRROR["current"] = url
                    try:
                        p = cached_datasheet(url, data_dir, client=client)
                        if p is None:
                            _MIRROR["failed"] += 1
                            if len(_MIRROR["errors"]) < 50:
                                _MIRROR["errors"].append(url)
                        else:
                            _MIRROR["ok"] += 1
                            if item_id:
                                ci = db.get(CatalogItem, item_id)
                                if ci and not (ci.specs or {}).get("datasheet_file"):
                                    sp = dict(ci.specs or {})
                                    sp["datasheet_file"] = p.name
                                    ci.specs = sp
                                    db.commit()
                    except Exception as e:  # noqa: BLE001
                        _MIRROR["failed"] += 1
                        if len(_MIRROR["errors"]) < 50:
                            _MIRROR["errors"].append(f"{url}: {e}")
                    _MIRROR["done"] += 1
                    time.sleep(0.2)
                client.close()
        finally:
            _MIRROR["running"] = False
            _MIRROR["current"] = None
            _MIRROR["finished_at"] = datetime.now(timezone.utc).isoformat()

    threading.Thread(target=run, name="datasheet-mirror", daemon=True).start()
    return True


def item_datasheet_path(ci: CatalogItem, download: bool = False) -> Path | None:
    sp = ci.specs or {}
    d = datasheet_cache_dir(get_settings().data_dir)
    if sp.get("datasheet_file"):
        p = d / sp["datasheet_file"]
        if p.exists():
            return p
    for u in _item_urls(ci):
        p = cached_datasheet(u, get_settings().data_dir, download=download)
        if p:
            return p
    return None


# ----------------------------------------------------------------------------- client package
def client_package(db: Session, q: Quote, *, merged_pdf: bool = True) -> tuple[bytes, str]:
    """ZIP for the client: quote PDF, technical file, layout render(s), datasheets of the main equipment and — when
    pypdf is available — one merged 'Пълно предложение' PDF with all of it in order."""
    from .pdf import render_quote_pdf
    from .techfile import render_techfile_pdf

    project = q.project
    quote_pdf = Path(render_quote_pdf(db, q, "client"))
    tech_pdf = Path(render_techfile_pdf(db, q))
    entries: list[tuple[str, bytes]] = [(f"01_Oferta_{q.number}_v{q.version}.pdf", quote_pdf.read_bytes()), (f"02_Tehnichesko_dosie_{q.number}_v{q.version}.pdf", tech_pdf.read_bytes())]
    pdfs = [quote_pdf, tech_pdf]
    n = 3
    for lay in project.layouts:
        if lay.render_path:
            p = get_settings().data_dir / lay.render_path
            if p.exists():
                entries.append((f"{n:02d}_Razpolozhenie_{_safe_name(lay.name)}.png", p.read_bytes()))
                n += 1
    seen: set[int] = set()
    seen_files: set[Path] = set()  # Aerocompact components share one system datasheet – include it once
    for l in q.lines:
        ci = l.catalog_item
        if bool(l.excluded) or not ci or ci.id in seen or ci.category not in ("panel", "inverter", "battery", "switchboard", "mounting"):
            continue
        if ci.category == "mounting" and not (ci.specs or {}).get("system"):
            continue
        p = item_datasheet_path(ci, download=True)
        if p and p.resolve() not in seen_files:
            seen.add(ci.id)
            seen_files.add(p.resolve())
            label = ci.name if ci.category != "mounting" else f"Aerocompact {(ci.specs or {}).get('system') or ''} {ci.name}".strip()
            entries.append((f"{n:02d}_Datasheet_{_safe_name(label)[:60]}.pdf", p.read_bytes()))
            pdfs.append(p)
            n += 1
    if merged_pdf:
        try:
            from pypdf import PdfWriter

            w = PdfWriter()
            for p in pdfs:
                w.append(str(p))
            buf = io.BytesIO()
            w.write(buf)
            entries.insert(0, (f"00_Palno_predlozhenie_{q.number}_v{q.version}.pdf", buf.getvalue()))
        except Exception:  # noqa: BLE001 – merging is a bonus
            pass
    zbuf = io.BytesIO()
    with zipfile.ZipFile(zbuf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in entries:
            z.writestr(name, data)
    data = zbuf.getvalue()
    archive(db, project, "quote", f"Paket_klient_{q.number}_v{q.version}.zip", data, quote=q, title=f"Пакет за клиента {q.number} v{q.version}")
    db.commit()
    return data, f"Paket_klient_{q.number}_v{q.version}.zip"
